def caller_context(default_operation: str, default_resource: str) -> tuple[str, str]:
    """Resolve the first CLI caller to its audited human labels."""
    frame = inspect.currentframe()
    try:
        frame = frame.f_back if frame else None
        while frame:
            module = str(frame.f_globals.get("__name__", ""))
            if module not in {"observal_cli.client", __name__}:
                function = frame.f_code.co_name
                filename = Path(frame.f_code.co_filename).name
                return OPERATION_LABELS.get(function, default_operation), RESOURCE_LABELS.get(
                    filename, default_resource
                )
            frame = frame.f_back
    finally:
        del frame
    return default_operation, default_resource
